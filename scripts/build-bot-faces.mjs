// The opponents' faces: an emoji per bot (Twemoji, CC BY 4.0) turned into pixel art. Each
// emoji is rendered with resvg, cut into a 24×24 grid, its colours spread over the four olive
// tones by brightness and an ink outline drawn around it. Writes src/play/bot-faces.data.ts.
// Run again after changing a face: `node scripts/build-bot-faces.mjs`.
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { Resvg } from '@resvg/resvg-js'

const ROOT = new URL('..', import.meta.url).pathname
const TWEMOJI = join(ROOT, 'node_modules/@twemoji/svg')
const OUT = join(ROOT, 'src/play/bot-faces.data.ts')
const GRID = 24
const SCALE = 16 // rendered pixels per cell side

// level 1 to 10, as in play/bots.ts
const FACES = [
  ['1f423', 'hatching chick'],
  ['1f916', 'robot'],
  ['1f63a', 'grinning cat'],
  ['1f3f0', 'castle'],
  ['1f469-200d-1f680', 'astronaut'],
  ['1f977', 'ninja'],
  ['1f9d9-200d-2640-fe0f', 'witch'],
  ['1f6e1', 'shield'],
  ['1f432', 'dragon'],
  ['1f47e', 'arcade monster'],
]

/** One face as rows of tones: k ink, d dark, m mid, l light, "." the tile. */
async function face(code) {
  const inner = GRID - 2 // one cell on each side for the outline
  const svg = (await readFile(join(TWEMOJI, `${code}.svg`), 'utf8')).replace('<svg', `<svg width="${inner * SCALE}" height="${inner * SCALE}"`)
  const r = new Resvg(svg).render()
  const px = r.pixels
  const cells = []
  for (let y = 0; y < inner; y++)
    for (let x = 0; x < inner; x++) {
      let alpha = 0
      let lum = 0
      for (let j = 0; j < SCALE; j++)
        for (let i = 0; i < SCALE; i++) {
          const k = ((y * SCALE + j) * r.width + x * SCALE + i) * 4
          const a = px[k + 3] / 255
          alpha += a
          lum += a * (0.2126 * px[k] + 0.7152 * px[k + 1] + 0.0722 * px[k + 2]) / 255
        }
      cells.push(alpha / (SCALE * SCALE) >= 0.5 ? lum / alpha : null)
    }
  // stretch the face's own brightness over the four tones, so a yellow chick keeps its eyes
  const lums = cells.filter((l) => l !== null).sort((a, b) => a - b)
  const lo = lums[Math.floor(lums.length * 0.03)]
  const hi = lums[Math.floor(lums.length * 0.97)]
  const tone = (l) => {
    const t = (l - lo) / (hi - lo || 1)
    return t < 0.18 ? 'k' : t < 0.45 ? 'd' : t < 0.78 ? 'm' : 'l'
  }
  const grid = Array.from({ length: GRID }, () => Array(GRID).fill('.'))
  cells.forEach((l, i) => {
    if (l !== null) grid[Math.floor(i / inner) + 1][(i % inner) + 1] = tone(l)
  })
  // the ink outline: every tile cell next to the face
  const near = (x, y) => [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => (grid[y + dy]?.[x + dx] ?? '.') !== '.')
  return grid.map((row, y) => row.map((c, x) => (c === '.' && near(x, y) ? 'k' : c)).join(''))
}

const faces = []
for (const [code, what] of FACES) faces.push(`  // ${what} (${code})\n  [\n${(await face(code)).map((row) => `    '${row}',`).join('\n')}\n  ],`)
await writeFile(
  OUT,
  `// Generated by scripts/build-bot-faces.mjs from Twemoji (CC BY 4.0); do not edit by hand.\n` +
    `// One face per level, ${GRID} rows of ${GRID} cells: k ink, d dark, m mid, l light, "." the tile.\n` +
    `export const BOT_FACES: string[][] = [\n${faces.join('\n')}\n]\n`,
)
console.log(FACES.length, 'faces')
