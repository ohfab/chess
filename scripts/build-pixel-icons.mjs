// Turns the lucide icons the app uses into pixel art: each icon is rendered large with
// resvg, then every cell of a 16- and a 24-cell grid is filled where the outline covers
// enough of it. The result keeps lucide's drawing, only in pixels, and is written to
// src/ui/pixel-icons.data.ts. Run again when an icon is added: `node scripts/build-pixel-icons.mjs`.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { Resvg } from '@resvg/resvg-js'

const ROOT = new URL('..', import.meta.url).pathname
const LUCIDE = join(ROOT, 'node_modules/lucide-react/dist/esm')
const OUT = join(ROOT, 'src/ui/pixel-icons.data.ts')

// every name imported from 'lucide-react' anywhere in src
async function usedNames(dir, names = new Set()) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) await usedNames(path, names)
    else if (/\.tsx?$/.test(entry.name) && !path.endsWith('pixel-icons.tsx')) {
      const src = await readFile(path, 'utf8')
      for (const m of src.matchAll(/import\s*\{([^}]+)\}\s*from\s*'lucide-react'/g))
        for (const part of m[1].split(',')) {
          const name = part.trim().replace(/^type\s+/, '').split(/\s+as\s+/)[0]
          if (name && name !== 'LucideIcon' && name !== 'LucideProps') names.add(name)
        }
    }
  }
  return names
}

// component name → icon module, from lucide's own export list (it knows the aliases, e.g. Loader2)
const exportsSrc = await readFile(join(LUCIDE, 'lucide-react.mjs'), 'utf8')
const fileOf = new Map()
for (const m of exportsSrc.matchAll(/export \{([^}]+)\} from '\.\/icons\/([^']+)'/g))
  for (const part of m[1].split(',')) fileOf.set(part.trim().replace(/^default as /, ''), m[2])

const attrs = (o) =>
  Object.entries(o)
    .filter(([k]) => k !== 'key')
    .map(([k, v]) => `${k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}="${v}"`)
    .join(' ')

/** Coverage of each grid cell (0..1) for the icon drawn with this stroke and fill. */
function cover(node, grid, { stroke, fill }) {
  const scale = 8
  const px = grid * scale
  const body = node.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join('')
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}" viewBox="0 0 24 24" fill="${fill ? '#000' : 'none'}" stroke="${stroke ? '#000' : 'none'}" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`
  const { pixels } = new Resvg(svg, { fitTo: { mode: 'original' } }).render()
  const cells = []
  for (let y = 0; y < grid; y++)
    for (let x = 0; x < grid; x++) {
      let sum = 0
      for (let j = 0; j < scale; j++) for (let i = 0; i < scale; i++) sum += pixels[((y * scale + j) * px + x * scale + i) * 4 + 3]
      cells.push(sum / (scale * scale * 255))
    }
  return cells
}

/** One path of row runs for the cells that are set. */
function runs(grid, on) {
  let d = ''
  for (let y = 0; y < grid; y++)
    for (let x = 0; x < grid; x++) {
      if (!on(x, y)) continue
      let w = 1
      while (x + w < grid && on(x + w, y)) w++
      d += `M${x} ${y}h${w}v1h${-w}z`
      x += w - 1
    }
  return d
}

// a 2-unit lucide stroke becomes 1 cell on the 16 grid and 2 cells on the 24 grid
const GRIDS = [
  { grid: 16, stroke: 1.5, threshold: 0.42 },
  { grid: 24, stroke: 2, threshold: 0.45 },
]

// icons the app draws filled (rush and blindfold lives, course stars, "this is me")
const FILLED = new Set(['Heart', 'Star'])

const names = [...(await usedNames(join(ROOT, 'src')))].sort()
const icons = {}
for (const name of names) {
  const file = fileOf.get(name)
  if (!file) throw new Error(`${name}: not a lucide icon`)
  const { __iconData } = await import(join(LUCIDE, 'icons', file))
  icons[name] = GRIDS.map(({ grid, stroke, threshold }) => {
    const line = cover(__iconData.node, grid, { stroke, fill: false })
    const area = cover(__iconData.node, grid, { stroke, fill: true })
    const isLine = (x, y) => line[y * grid + x] >= threshold
    // the inside shows only where a caller fills the icon; only shapes the app fills get one
    const isInside = (x, y) => FILLED.has(name) && !isLine(x, y) && area[y * grid + x] >= 0.5
    return [runs(grid, isLine), runs(grid, isInside)]
  })
}

const body = Object.entries(icons)
  .map(([name, [small, large]]) => `  ${name}: [${JSON.stringify(small[0])}, ${JSON.stringify(small[1])}, ${JSON.stringify(large[0])}, ${JSON.stringify(large[1])}],`)
  .join('\n')
await writeFile(
  OUT,
  `// Generated by scripts/build-pixel-icons.mjs from lucide (ISC license); do not edit by hand.\n` +
    `// Per icon: outline and inside on the 16 grid, then outline and inside on the 24 grid.\n` +
    `export const ICONS: Record<string, [string, string, string, string]> = {\n${body}\n}\n`,
)
const shim = await readFile(join(ROOT, 'src/ui/pixel-icons.tsx'), 'utf8')
const missing = names.filter((n) => !shim.includes(`export const ${n} = icon('${n}')`))
